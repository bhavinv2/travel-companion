"""Hard delete for admins: permanent removal of any record shown in the admin panel or CS console.

Two layers:

  cascades      delete_post_cascade and delete_user_cascade, and a small cascade per kind below.
                They never commit. They do NOT rely on database ON DELETE behaviour -- some foreign
                keys cascade, many don't, and they were added across several phases -- so every
                dependent row is deleted, detached or anonymised explicitly, in an order PostgreSQL
                accepts with its foreign keys enforced. (The tests run SQLite, which does not
                enforce them by default; tests/test_admin_hard_delete.py switches enforcement on.)

  the registry  KINDS maps a name ('post', 'contact_message', ...) to how to find, guard, cascade
                and log one row. hard_delete(kind, ids, actor) is the single entry point every
                delete button in both consoles goes through: one admin check, one audit format,
                one commit, files removed only after the commit succeeds.

Nothing here is reversible; callers confirm intent first (the type-DELETE dialog for anything with
dependants, a plain confirm for a leaf row).

What is deliberately NOT deletable, and why:
  Match / MatchParty   regenerated by the matcher on the next look at a post -- a deleted match
                       comes straight back. Dismiss is the removal that lasts.
  TripLeg              derived from the post and rebuilt on every save.
  ContactPoint         edited and removed on the post form already.
  ContactReply         the record of an e-mail that was actually sent; goes with its enquiry.
  Chats                private conversations between two people, shown on no staff screen.
  AppSetting           configuration, each blob with its own editor.
"""
from dataclasses import dataclass, field
from typing import Callable, Optional

from app import db


