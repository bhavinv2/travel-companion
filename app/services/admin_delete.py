def delete_post_cascade(trip, files=None):
    """Permanently delete one CompanionRequest and everything that only makes sense with it.

    `files`, when given, collects what to remove from storage AFTER the commit (a rolled-back
    delete must not have already destroyed the ticket it would have kept).

    Chats are kept and detached, not deleted: a chat room belongs to a PAIR of people and is reused
    across all their posts (ChatRoom.get_or_create), so deleting the rooms of one post wiped that
    pair's whole conversation, including what they said about other trips.
    """
    from app.models import (ContactPoint, ClaimToken, ConnectionRequest, ChatRoom,
                            ActivityEvent, TripLeg, Notification, ScrapeRow)
    trip_id = trip.id

    _delete_matches_for_trip_ids([trip_id])

    conn_ids = [c.id for c in ConnectionRequest.query.filter_by(trip_id=trip_id).all()]
    if conn_ids:
        Notification.query.filter(Notification.connection_id.in_(conn_ids)) \
            .update({'connection_id': None}, synchronize_session=False)
        ConnectionRequest.query.filter(ConnectionRequest.id.in_(conn_ids)).delete(synchronize_session=False)

    ChatRoom.query.filter_by(trip_id=trip_id).update({'trip_id': None}, synchronize_session=False)

    ContactPoint.query.filter_by(trip_id=trip_id).delete(synchronize_session=False)
    ClaimToken.query.filter_by(trip_id=trip_id).delete(synchronize_session=False)
    ActivityEvent.query.filter_by(trip_id=trip_id).delete(synchronize_session=False)
    TripLeg.query.filter_by(trip_id=trip_id).delete(synchronize_session=False)
    # a scraped row whose post is gone is third-party data with no reason to keep: mark it skipped
    # so the retention job purges it on schedule (it keeps 'imported' rows forever)
    for col in (ScrapeRow.duplicate_of_id, ScrapeRow.imported_post_id):
        ScrapeRow.query.filter(col == trip_id, ScrapeRow.status.in_(('imported', 'duplicate'))) \
            .update({'status': 'skipped'}, synchronize_session=False)
    ScrapeRow.query.filter_by(duplicate_of_id=trip_id).update({'duplicate_of_id': None}, synchronize_session=False)
    ScrapeRow.query.filter_by(imported_post_id=trip_id).update({'imported_post_id': None}, synchronize_session=False)

    if files is not None and trip.ticket_attachment:
        files.append(('private', trip.ticket_attachment))
    db.session.delete(trip)


def delete_user_cascade(user, actor=None, files=None):
    """Permanently delete a user, everything that is theirs, and anonymise their footprint in other
    people's records.

    Ordered for PostgreSQL. The old version missed several references that only PostgreSQL
    enforces (posts a CS agent created, enquiries they handled, bookings they assigned, settings
    an admin saved, notifications about their connection requests), so deleting nearly any staff
    account raised an IntegrityError in production while passing every SQLite test.

    Blog posts written by the user are REASSIGNED to the acting admin rather than deleted:
    deleting an admin used to silently wipe the public blog posts they had written.
    """
    from app.models import (CompanionRequest, Feedback, ChatRoom, ChatMessage, Notification,
                            ConnectionRequest, ContactPoint, ActivityEvent, ClaimToken,
                            MatchParty, Match, MatchReport, Blog, ContactMessage, ContactReply,
                            InsuranceQuote, SahayakBooking, SavedFilter, AppSetting, StaffRead)
    user_id = user.id

    # 1. their posts, with everything tied to them
    for trip in CompanionRequest.query.filter_by(user_id=user_id).all():
        delete_post_cascade(trip, files)
    # 2. posts they created for someone else (CS, imports) stay; the creator is forgotten
    CompanionRequest.query.filter_by(created_by_id=user_id).update({'created_by_id': None}, synchronize_session=False)
    CompanionRequest.query.filter_by(closed_by_id=user_id).update({'closed_by_id': None}, synchronize_session=False)

    # 3. connection requests they made -- notifications about them first
    conn_ids = [c.id for c in ConnectionRequest.query.filter_by(requester_id=user_id).all()]
    if conn_ids:
        Notification.query.filter(Notification.connection_id.in_(conn_ids)) \
            .update({'connection_id': None}, synchronize_session=False)
        ConnectionRequest.query.filter(ConnectionRequest.id.in_(conn_ids)).delete(synchronize_session=False)

    # 4. their chats: every room they are in, with its messages and attachments
    room_ids = [r.id for r in ChatRoom.query.filter(
        db.or_(ChatRoom.user1_id == user_id, ChatRoom.user2_id == user_id)).all()]
    if room_ids:
        if files is not None:
            for (url,) in db.session.query(ChatMessage.file_url).filter(
                    ChatMessage.room_id.in_(room_ids), ChatMessage.file_url.isnot(None)).all():
                files.append(('public', url))
        ChatMessage.query.filter(ChatMessage.room_id.in_(room_ids)).delete(synchronize_session=False)
        ChatRoom.query.filter(ChatRoom.id.in_(room_ids)).delete(synchronize_session=False)

    # 5. their own records
    Notification.query.filter_by(user_id=user_id).delete(synchronize_session=False)
    fb_ids = [f.id for f in Feedback.query.filter_by(user_id=user_id).all()]
    _forget_reads('feedback', fb_ids)
    Feedback.query.filter_by(user_id=user_id).delete(synchronize_session=False)
    ContactPoint.query.filter_by(user_id=user_id).delete(synchronize_session=False)
    SavedFilter.query.filter_by(owner_id=user_id).delete(synchronize_session=False)
    StaffRead.query.filter_by(user_id=user_id).delete(synchronize_session=False)

    # 6. the blog keeps its posts: reassigned to whoever is deleting (author_id is NOT NULL)
    if actor is not None and getattr(actor, 'id', None) and actor.id != user_id:
        Blog.query.filter_by(author_id=user_id).update({'author_id': actor.id}, synchronize_session=False)
    else:
        Blog.query.filter_by(author_id=user_id).delete(synchronize_session=False)

    # 7. what they sent us: enquiries (with replies), insurance quotes, Sahayak bookings
    msg_ids = [m.id for m in ContactMessage.query.filter_by(user_id=user_id).all()]
    if msg_ids:
        _forget_reads('contact', msg_ids)
        ContactReply.query.filter(ContactReply.message_id.in_(msg_ids)).delete(synchronize_session=False)
        ContactMessage.query.filter(ContactMessage.id.in_(msg_ids)).delete(synchronize_session=False)
    InsuranceQuote.query.filter_by(user_id=user_id).delete(synchronize_session=False)
    SahayakBooking.query.filter_by(user_id=user_id).delete(synchronize_session=False)

    # 8. their footprint in other people's records: anonymised, so that history stays intact
    for col in (ActivityEvent.actor_id, ClaimToken.created_by_id, MatchParty.sent_by_id,
                Match.cs_owner_id, MatchReport.reporter_id, MatchReport.resolved_by_id,
                ContactMessage.handled_by_id, ContactReply.author_id,
                SahayakBooking.assigned_by_id, AppSetting.updated_by_id):
        col.class_.query.filter(col == user_id).update({col.key: None}, synchronize_session=False)
    try:
        from app.models import ScrapeRow, ScrapeRecipe, ScrapeRun
        ScrapeRow.query.filter_by(imported_by_id=user_id).update({'imported_by_id': None}, synchronize_session=False)
        ScrapeRecipe.query.filter_by(created_by_id=user_id).update({'created_by_id': None}, synchronize_session=False)
        ScrapeRun.query.filter_by(started_by_id=user_id).update({'started_by_id': None}, synchronize_session=False)
    except ImportError:      # pragma: no cover - scraper models optional
        pass

    # 9. their uploaded photo (never an OAuth provider's URL)
    if files is not None and user.photo_url:
        files.append(('public', user.photo_url))
    db.session.delete(user)


