def _forget_reads(read_kind, ids):
    """Drop staff "has opened this" marks for rows that no longer exist. They point at rows by a
    plain id with no foreign key, so nothing else would ever clear them."""
    from app.models import StaffRead
    ids = [i for i in (ids or []) if i is not None]
    if ids:
        StaffRead.query.filter(StaffRead.kind == read_kind, StaffRead.item_id.in_(ids)) \
            .delete(synchronize_session=False)


def _delete_matches(match_ids):
    """Matches and everything hanging off them: reports, parties, read marks."""
    from app.models import Match, MatchParty, MatchReport
    match_ids = list(match_ids or [])
    if not match_ids:
        return
    report_ids = [r.id for r in MatchReport.query.filter(MatchReport.match_id.in_(match_ids)).all()]
    _forget_reads('report', report_ids)
    _forget_reads('match', match_ids)
    MatchReport.query.filter(MatchReport.match_id.in_(match_ids)).delete(synchronize_session=False)
    MatchParty.query.filter(MatchParty.match_id.in_(match_ids)).delete(synchronize_session=False)
    Match.query.filter(Match.id.in_(match_ids)).delete(synchronize_session=False)


def _delete_matches_for_trip_ids(trip_ids):
    """Remove every Match touching any of these posts, plus its parties and reports."""
    from app.models import Match, MatchParty, MatchReport
    trip_ids = list(trip_ids or [])
    if not trip_ids:
        return
    match_ids = [m.id for m in Match.query.filter(
        db.or_(Match.trip_a_id.in_(trip_ids), Match.trip_b_id.in_(trip_ids))).all()]
    _delete_matches(match_ids)
    # belt and braces: parties and reports are always tied to a match touching the post, but both
    # also carry trip_id, and a NOT NULL / un-cascaded trip_id left behind would block the delete
    MatchReport.query.filter(MatchReport.trip_id.in_(trip_ids)).delete(synchronize_session=False)
    MatchParty.query.filter(MatchParty.trip_id.in_(trip_ids)).delete(synchronize_session=False)


