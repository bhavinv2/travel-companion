@dataclass
class Kind:
    model: Callable                     # returns the model class (imported lazily)
    noun: str                           # what one of these is called on screen
    event: str                          # the audit event, <= 40 chars
    label: Callable = lambda o: '#%s' % o.id
    tier: str = 'confirm'               # 'type' = the type-DELETE dialog; 'confirm' = a plain confirm
    guard: Optional[Callable] = None    # (obj, actor) -> error string or None
    cascade: Optional[Callable] = None  # (obj, actor, files) -> None; default: delete the row
    after: Optional[Callable] = None    # (objs) -> None, before the commit, once per batch
    meta: Callable = lambda o: {}


def _m(name):
    def get():
        from app import models
        return getattr(models, name)
    return get


def _guard_user(user, actor):
    if actor is not None and user.id == actor.id:
        return 'You cannot delete your own account.'
    return None


def _cascade_contact(msg, actor, files):
    """The replies go through the ORM, not a bulk delete: `replies` loads with the enquiry
    (selectin), and the relationship's cascade then deletes those same rows again -- a second
    delete that matches nothing and warns."""
    _forget_reads('contact', [msg.id])
    for reply in list(msg.replies):
        db.session.delete(reply)
    db.session.delete(msg)


def delete_feedback(fb, actor=None, files=None):
    """A review and the read marks on it. Public because Reject -- which any agent with the
    voices screen may do -- is this same delete, on both consoles."""
    _forget_reads('feedback', [fb.id])
    db.session.delete(fb)


def _cascade_report(report, actor, files):
    """A deleted report must not leave its match stuck in the CS queue: when it was the last open
    report on that match, the match stops needing attention -- exactly what resolving it does."""
    from app.models import Match, MatchReport
    _forget_reads('report', [report.id])
    match_id = report.match_id
    db.session.delete(report)
    db.session.flush()
    if match_id and not MatchReport.query.filter_by(match_id=match_id, status='open').count():
        m = db.session.get(Match, match_id)
        if m is not None and m.needs_cs_attention:
            m.needs_cs_attention = False


def _cascade_blog(blog, actor, files):
    """Notifications pointing at the post would open a 404."""
    from app.models import Notification
    if blog.slug:
        Notification.query.filter(Notification.link == '/blog/%s' % blog.slug) \
            .delete(synchronize_session=False)
    db.session.delete(blog)


MANUAL_EVENTS = ('note', 'dm_sent', 'called', 'claim_link_sent_manual')


def _guard_event(ev, actor):
    if ev.event not in MANUAL_EVENTS:
        return 'System events are the audit trail and cannot be deleted.'
    return None


def _guard_scrape_active(run, actor):
    if run.status in ('queued', 'running'):
        return 'That run is still going -- cancel it first.'
    return None


def _guard_recipe(recipe, actor):
    from app.models import ScrapeRun
    if ScrapeRun.query.filter(ScrapeRun.recipe_id == recipe.id,
                              ScrapeRun.status.in_(('queued', 'running'))).count():
        return 'A run of this recipe is still going -- cancel it first.'
    return None


def _cascade_run(run, actor, files):
    """Its rows first: ScrapeRun.rows has no cascade and run_id is NOT NULL. A teach run's
    saved_path is NOT removed -- it is the recipe's own saved browser session, which later runs
    still sign in with; it goes when the recipe does."""
    from app.models import ScrapeRow
    ScrapeRow.query.filter_by(run_id=run.id).delete(synchronize_session=False)
    db.session.delete(run)


def _cascade_recipe(recipe, actor, files):
    """Bulk deletes, not the ORM cascade: a big recipe's rows would all be loaded one by one."""
    from app.models import ScrapeRow, ScrapeRun, ScrapeRecipe
    if files is not None and getattr(recipe, 'session_key', None):
        others = ScrapeRecipe.query.filter(ScrapeRecipe.session_key == recipe.session_key,
                                           ScrapeRecipe.id != recipe.id).count()
        if not others:
            files.append(('scraper_session', recipe.session_key))
    ScrapeRow.query.filter_by(recipe_id=recipe.id).delete(synchronize_session=False)
    ScrapeRun.query.filter_by(recipe_id=recipe.id).delete(synchronize_session=False)
    db.session.delete(recipe)


